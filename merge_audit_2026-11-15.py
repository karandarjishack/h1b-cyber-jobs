# Held entries moving to excluded.md (removed from held here; the
# excluded.md append happens in a separate step).
EXCLUDED_TITLES = [
    ("General Motors", "Senior SaaS & AI Cyber Security Engineer"),
    ("Motiva", "Sr. Cybersecurity Analyst, Detection & Response"),
    ("Amazon", "Security Engineer, SBS Pentesting"),
]


def main():
    seed = json.load(open(ROOT / "jobs_seed.json"))
    held = json.load(open(ROOT / "held_jobs.json"))

    seed_ids = {j["id"] for j in seed}
    dupes = [j["id"] for j in NEW_JOBS if j["id"] in seed_ids]
    assert not dupes, f"duplicate seed ids: {dupes}"
    seed.extend(NEW_JOBS)

    held_ids = {h["id"] for h in held}
    missing_unhold = [i for i in UNHOLD_IDS if i not in held_ids]
    assert not missing_unhold, f"un-hold ids not in held: {missing_unhold}"
    held = [h for h in held if h["id"] not in set(UNHOLD_IDS)]

    # Move the three newly-excluded roles out of held.
    moved = []
    kept = []
    for h in held:
        if any(h["employer"].startswith(e) and t in h["title"]
               for e, t in EXCLUDED_TITLES):
            moved.append(h["id"])
        else:
            kept.append(h)
    held = kept
    print("moved held -> excluded:", moved)

    # Sentry AppSec stays held: my own check of the Ashby URL shows the
    # salary in CAD ($162,000-$200,000 CAD) - it is the Toronto variant,
    # not the US SF role. Update the reason so nobody lists it as US.
    for h in held:
        if h["id"] == "sentry-sec-eng-appsec-2026-11":
            h["held_reason"] = (
                "STILL HELD Nov 15, 2026 - the Ashby URL on file is the "
                "TORONTO/CAD variant (salary $162,000-$200,000 CAD on the "
                "page), not the US San Francisco role. Do NOT list it as a "
                "US role. Hunt for the US SF variant's own Ashby URL."
            )

    # Add the new held entries (skip any id already present).
    held_ids = {h["id"] for h in held}
    dupes = [h["id"] for h in NEW_HELD if h["id"] in held_ids]
    assert not dupes, f"duplicate held ids: {dupes}"
    held.extend(NEW_HELD)

    # Held hygiene (audit fix): stamp last_checked on every remaining entry.
    for h in held:
        h.setdefault("last_checked", "2026-11-15")

    json.dump(seed, open(ROOT / "jobs_seed.json", "w"), indent=2)
    json.dump(held, open(ROOT / "held_jobs.json", "w"), indent=2)
    live_holds = sum(
        1 for h in held
        if not str(h.get("held_reason", "")).startswith("CLOSED")
    )
    print(f"seed jobs: {len(seed)}")
    print(f"held entries: {len(held)} ({live_holds} live, "
          f"{len(held) - live_holds} closed records)")
    print(f"new seed jobs added: {len(NEW_JOBS)}")
    print(f"new held entries added: {len(NEW_HELD)}")


if __name__ == "__main__":
    main()
